import type { Logger } from "@penumbra/core";

import { createDispatchPR } from "@src/worker/github-pr-helper.js";
import { expect, mock, test } from "bun:test";
import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";

const noopLogger = (): void => {
  // intentionally empty: silent logger for github-pr-helper tests
};

function silentLogger(): Logger {
  return { error: mock(noopLogger) } as unknown as Logger;
}

interface RunnerCall {
  file: string;
  args: string[];
  cwd: string;
}

test("createDispatchPR pushes the branch and creates a PR with a body file", async () => {
  const calls: RunnerCall[] = [];
  let bodyFilePath = "";
  const runner = {
    run: mock(async (file: string, args: string[], options: { cwd: string }) => {
      calls.push({ file, args, cwd: options.cwd });

      if (file === "gh") {
        const bodyFileIndex = args.indexOf("--body-file");
        expect(bodyFileIndex).toBeGreaterThanOrEqual(0);
        bodyFilePath = args[bodyFileIndex + 1]!;
        const body = await readFile(bodyFilePath, "utf8");
        expect(body).toContain("## Dispatched");
        expect(body).toContain("- **agent:** codex-mini");
        expect(body).toContain("- **handoff:** h-123");
        expect(body).toContain("- **conversation:** c-456");
        expect(body).toContain("dispatch prompt with $(touch /tmp/pwned) literally");
        expect(body).toContain("- typecheck: pass");
        expect(body).toContain("- tests: bun test packages/daemon/test/ → pass");
        expect(body).toContain("1 file changed, 2 insertions(+), 1 deletion(-)");
        return {
          stdout: "https://github.com/frozename/penumbra/pull/321\n",
          stderr: "",
          code: 0,
        };
      }

      return {
        stdout: "",
        stderr: "",
        code: 0,
      };
    }),
  };

  const result = await createDispatchPR(
    {
      branch: "agent/h-123",
      baseBranch: "main",
      title: "[codex-mini] dispatch prompt with $(touch /tmp/pwned) literally",
      body: [
        "## Dispatched",
        "- **agent:** codex-mini",
        "- **handoff:** h-123",
        "- **conversation:** c-456",
        "",
        "## Prompt",
        "<details><summary>Click to expand (1 lines)</summary>",
        "",
        "dispatch prompt with $(touch /tmp/pwned) literally",
        "</details>",
        "",
        "## Reconciler results",
        "- typecheck: pass",
        "- tests: bun test packages/daemon/test/ → pass",
        "",
        "## Diff",
        "1 file changed, 2 insertions(+), 1 deletion(-)",
        "",
        "---",
        "🤖 Auto-generated by penumbra reconciler",
        "",
      ].join("\n"),
      draft: false,
      cwd: "/worktree/h-123",
    },
    silentLogger(),
    runner,
  );

  expect(result).toEqual({
    url: "https://github.com/frozename/penumbra/pull/321",
    number: 321,
  });
  expect(calls).toHaveLength(2);
  expect(calls[0]).toEqual({
    file: "git",
    args: ["push", "-u", "origin", "agent/h-123"],
    cwd: "/worktree/h-123",
  });
  expect(calls[1]).toEqual({
    file: "gh",
    args: [
      "pr",
      "create",
      "--base",
      "main",
      "--head",
      "agent/h-123",
      "--title",
      "[codex-mini] dispatch prompt with $(touch /tmp/pwned) literally",
      "--body-file",
      bodyFilePath,
    ],
    cwd: "/worktree/h-123",
  });
  expect(existsSync(bodyFilePath)).toBe(false);
});

test("createDispatchPR removes the temp body file when gh fails", async () => {
  let bodyFilePath = "";
  const runner = {
    run: mock((file: string, args: string[]) => {
      if (file === "gh") {
        const bodyFileIndex = args.indexOf("--body-file");
        bodyFilePath = args[bodyFileIndex + 1]!;
        expect(existsSync(bodyFilePath)).toBe(true);
        return Promise.resolve({
          stdout: "",
          stderr: "fatal: auth required",
          code: 1,
        });
      }

      return Promise.resolve({
        stdout: "",
        stderr: "",
        code: 0,
      });
    }),
  };

  let caughtMessage: string | null = null;
  try {
    await createDispatchPR(
      {
        branch: "agent/h-404",
        baseBranch: "main",
        title: "[codex-mini] failed dispatch",
        body: "body",
        draft: true,
        cwd: "/worktree/h-404",
      },
      silentLogger(),
      runner,
    );
  } catch (err) {
    if (err instanceof Error) caughtMessage = err.message;
  }
  expect(caughtMessage).toBe("gh pr create failed (1): fatal: auth required");

  expect(bodyFilePath).not.toBe("");
  expect(existsSync(bodyFilePath)).toBe(false);
});
