import { describe, expect, test } from "bun:test";

import { type DispatchPRBodyInput, renderDispatchPRBody } from "@src/worker/github-pr-helper.js";

function inputWith(overrides: Partial<DispatchPRBodyInput>): DispatchPRBodyInput {
  return {
    agentName: "codex-mini",
    handoffId: "h-123",
    conversationId: "c-456",
    prompt: "do the thing",
    typecheckStatus: "pass",
    testCommand: "bun test packages/daemon/test/",
    testSummary: "pass",
    diffStats: "1 file changed, 2 insertions(+), 1 deletion(-)",
    ...overrides,
  };
}

describe("renderDispatchPRBody header and results section", () => {
  test("renders agent, handoff and conversation identity lines", () => {
    const body = renderDispatchPRBody(inputWith({}));
    expect(body).toContain("## Dispatched\n");
    expect(body).toContain("- **agent:** codex-mini\n");
    expect(body).toContain("- **handoff:** h-123\n");
    expect(body).toContain("- **conversation:** c-456\n");
  });

  test("null conversation renders as <unknown>", () => {
    const body = renderDispatchPRBody(inputWith({ conversationId: null }));
    expect(body).toContain("- **conversation:** <unknown>\n");
  });

  test("renders typecheck and test command summary lines", () => {
    const body = renderDispatchPRBody(inputWith({}));
    expect(body).toContain("- typecheck: pass\n");
    expect(body).toContain("- tests: bun test packages/daemon/test/ → pass\n");
  });

  test("body ends with the reconciler footer", () => {
    const body = renderDispatchPRBody(inputWith({}));
    expect(body.endsWith("---\n🤖 Auto-generated by penumbra reconciler\n")).toBe(true);
  });
});

describe("renderDispatchPRBody prompt handling", () => {
  test("trailing whitespace on the prompt is trimmed before rendering", () => {
    const body = renderDispatchPRBody(inputWith({ prompt: "do the thing\n\n  \n" }));
    expect(body).toContain("do the thing\n</details>");
    expect(body).toContain("<details><summary>Click to expand (1 lines)</summary>");
  });

  test("multi-line prompt line count excludes trailing blank lines", () => {
    const body = renderDispatchPRBody(inputWith({ prompt: "line one\nline two\n\n\n" }));
    expect(body).toContain("<details><summary>Click to expand (2 lines)</summary>");
    expect(body).toContain("line one\nline two\n</details>");
  });

  test("prompt that is only whitespace renders as <empty> with zero lines", () => {
    const body = renderDispatchPRBody(inputWith({ prompt: "  \n\n" }));
    expect(body).toContain("<details><summary>Click to expand (0 lines)</summary>");
    expect(body).toContain("<empty>\n</details>");
  });

  test("fully empty prompt renders as <empty>", () => {
    const body = renderDispatchPRBody(inputWith({ prompt: "" }));
    expect(body).toContain("<empty>\n</details>");
  });
});

describe("renderDispatchPRBody diff stats handling", () => {
  test("surrounding whitespace on diff stats is trimmed", () => {
    const body = renderDispatchPRBody(inputWith({ diffStats: "\n  1 file changed  \n" }));
    expect(body).toContain("## Diff\n1 file changed\n");
  });

  test("whitespace-only diff stats fall back to <unavailable>", () => {
    const body = renderDispatchPRBody(inputWith({ diffStats: "   \n\t\n" }));
    expect(body).toContain("## Diff\n<unavailable>\n");
  });

  test("empty diff stats fall back to <unavailable>", () => {
    const body = renderDispatchPRBody(inputWith({ diffStats: "" }));
    expect(body).toContain("## Diff\n<unavailable>\n");
  });
});
