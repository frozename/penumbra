import type { Logger } from "@penumbra/core";

import { spawn } from "node:child_process";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";

export interface CreatePRArgs {
  branch: string;
  baseBranch: string;
  title: string;
  body: string;
  draft: boolean;
  cwd: string;
}

export interface CreatePRResult {
  url: string;
  number: number;
}

interface SpawnRunner {
  run: (
    file: string,
    args: string[],
    options: { cwd: string; env?: Record<string, string> },
  ) => Promise<{ stdout: string; stderr: string; code: number }>;
}

/** Default array-args spawn runner. No shell - eliminates injection risk. */
export const defaultSpawnRunner: SpawnRunner = {
  run: (file, args, options) =>
    new Promise((resolve, reject) => {
      const proc = spawn(file, args, { cwd: options.cwd, shell: false, env: options.env });
      let stdout = "";
      let stderr = "";

      proc.stdout.on("data", (d: Buffer | string) => {
        stdout += typeof d === "string" ? d : d.toString();
      });
      proc.stderr.on("data", (d: Buffer | string) => {
        stderr += typeof d === "string" ? d : d.toString();
      });
      proc.on("error", reject);
      proc.on("close", (code) => {
        resolve({ stdout, stderr, code: code ?? -1 });
      });
    }),
};

/** The PR base is not a branch on `origin`; raised before anything is pushed. */
export class PRBaseUnavailableError extends Error {
  readonly code = "pr_base_unavailable" as const;
  readonly baseBranch: string;

  constructor(baseBranch: string) {
    super(`PR base branch "${baseBranch}" does not exist on origin`);
    this.name = "PRBaseUnavailableError";
    this.baseBranch = baseBranch;
  }
}

// Handoffs record the base as a local ref (`origin/main`, `refs/heads/main`),
// but `gh pr create --base` and the remote probe need the bare branch name.
const LOCAL_BASE_PREFIXES = ["refs/remotes/origin/", "refs/heads/", "origin/"] as const;

export function normalizePRBase(baseBranch: string): string {
  for (const prefix of LOCAL_BASE_PREFIXES) {
    if (baseBranch.startsWith(prefix)) return baseBranch.slice(prefix.length);
  }
  return baseBranch;
}

async function assertBaseOnRemote(base: string, cwd: string, runner: SpawnRunner): Promise<void> {
  // ls-remote matches patterns against ref-name tails, so a bare `main` would
  // also accept `refs/heads/x/main`; the fully qualified ref pins the branch.
  const probe = await runner.run(
    "git",
    ["ls-remote", "--exit-code", "--heads", "origin", `refs/heads/${base}`],
    { cwd },
  );
  if (probe.code === 0) return;
  // --exit-code reserves 2 for "no matching ref"; anything else means the
  // remote could not be asked, which says nothing about the base itself.
  if (probe.code === 2) throw new PRBaseUnavailableError(base);
  throw new Error(`git ls-remote failed (${String(probe.code)}): ${probe.stderr.slice(0, 500)}`);
}

export interface DispatchPRBodyInput {
  agentName: string;
  handoffId: string;
  conversationId: string | null;
  prompt: string;
  typecheckStatus: string;
  testCommand: string;
  testSummary: string;
  diffStats: string;
}

export function renderDispatchPRBody(input: DispatchPRBodyInput): string {
  const prompt = input.prompt.trimEnd();
  const promptLineCount = prompt === "" ? 0 : prompt.split("\n").length;
  const diffStats = input.diffStats.trim() || "<unavailable>";

  return [
    "## Dispatched",
    `- **agent:** ${input.agentName}`,
    `- **handoff:** ${input.handoffId}`,
    `- **conversation:** ${input.conversationId ?? "<unknown>"}`,
    "",
    "## Prompt",
    `<details><summary>Click to expand (${String(promptLineCount)} lines)</summary>`,
    "",
    prompt || "<empty>",
    "</details>",
    "",
    "## Reconciler results",
    `- typecheck: ${input.typecheckStatus}`,
    `- tests: ${input.testCommand} → ${input.testSummary}`,
    "",
    "## Diff",
    diffStats,
    "",
    "---",
    "🤖 Auto-generated by penumbra reconciler",
    "",
  ].join("\n");
}

export async function createDispatchPR(
  args: CreatePRArgs,
  log: Logger,
  runner: SpawnRunner = defaultSpawnRunner,
): Promise<CreatePRResult> {
  const bodyFile = path.join(
    os.tmpdir(),
    `penumbra-pr-body-${String(Date.now())}-${Math.random().toString(36).slice(2)}.md`,
  );

  try {
    const base = normalizePRBase(args.baseBranch);
    await assertBaseOnRemote(base, args.cwd, runner);

    const push = await runner.run("git", ["push", "-u", "origin", args.branch], { cwd: args.cwd });
    if (push.code !== 0) {
      throw new Error(`git push failed (${String(push.code)}): ${push.stderr.slice(0, 500)}`);
    }

    await fs.writeFile(bodyFile, args.body, "utf8");

    const ghArgs = [
      "pr",
      "create",
      "--base",
      base,
      "--head",
      args.branch,
      "--title",
      args.title,
      "--body-file",
      bodyFile,
    ];
    if (args.draft) ghArgs.push("--draft");

    const create = await runner.run("gh", ghArgs, { cwd: args.cwd });
    if (create.code !== 0) {
      throw new Error(
        `gh pr create failed (${String(create.code)}): ${create.stderr.slice(0, 500)}`,
      );
    }

    const url = create.stdout.trim();
    const numberMatch = /\/pull\/(\d+)/.exec(url);
    if (!numberMatch) {
      log.error({ url, stderr: create.stderr }, "failed to parse PR number from gh output");
      throw new Error(`gh pr create returned unparseable output: ${url}`);
    }

    return { url, number: Number(numberMatch[1]) };
  } finally {
    await fs.rm(bodyFile, { force: true }).catch((): void => {
      /* best-effort cleanup */
    });
  }
}
