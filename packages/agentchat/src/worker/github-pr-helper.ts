import { spawn } from "node:child_process";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import type { Logger } from "@penumbra/core";

export interface CreatePRArgs {
  branch: string;
  baseBranch: string;
  title: string;
  body: string;
  draft: boolean;
  cwd: string;
}

export interface CreatePRResult {
  url: string;
  number: number;
}

interface SpawnRunner {
  run: (
    file: string,
    args: string[],
    options: { cwd: string; env?: Record<string, string> },
  ) => Promise<{ stdout: string; stderr: string; code: number }>;
}

/** Default array-args spawn runner. No shell - eliminates injection risk. */
export const defaultSpawnRunner: SpawnRunner = {
  run: (file, args, options) =>
    new Promise((resolve, reject) => {
      const proc = spawn(file, args, { cwd: options.cwd, shell: false, env: options.env });
      let stdout = "";
      let stderr = "";

      proc.stdout?.on("data", (d) => {
        stdout += d.toString();
      });
      proc.stderr?.on("data", (d) => {
        stderr += d.toString();
      });
      proc.on("error", reject);
      proc.on("close", (code) => {
        resolve({ stdout, stderr, code: code ?? -1 });
      });
    }),
};

export interface DispatchPRBodyInput {
  agentName: string;
  handoffId: string;
  conversationId: string | null;
  prompt: string;
  typecheckStatus: string;
  testCommand: string;
  testSummary: string;
  diffStats: string;
}

export function renderDispatchPRBody(input: DispatchPRBodyInput): string {
  const prompt = input.prompt.trimEnd();
  const promptLineCount = prompt === "" ? 0 : prompt.split("\n").length;
  const diffStats = input.diffStats.trim() || "<unavailable>";

  return [
    "## Dispatched",
    `- **agent:** ${input.agentName}`,
    `- **handoff:** ${input.handoffId}`,
    `- **conversation:** ${input.conversationId ?? "<unknown>"}`,
    "",
    "## Prompt",
    `<details><summary>Click to expand (${promptLineCount} lines)</summary>`,
    "",
    prompt || "<empty>",
    "</details>",
    "",
    "## Reconciler results",
    `- typecheck: ${input.typecheckStatus}`,
    `- tests: ${input.testCommand} → ${input.testSummary}`,
    "",
    "## Diff",
    diffStats,
    "",
    "---",
    "🤖 Auto-generated by penumbra reconciler",
    "",
  ].join("\n");
}

export async function createDispatchPR(
  args: CreatePRArgs,
  log: Logger,
  runner: SpawnRunner = defaultSpawnRunner,
): Promise<CreatePRResult> {
  const bodyFile = path.join(
    os.tmpdir(),
    `penumbra-pr-body-${Date.now()}-${Math.random().toString(36).slice(2)}.md`,
  );

  try {
    await runner.run("git", ["push", "-u", "origin", args.branch], { cwd: args.cwd });

    await fs.writeFile(bodyFile, args.body, "utf8");

    const ghArgs = [
      "pr",
      "create",
      "--base",
      args.baseBranch,
      "--head",
      args.branch,
      "--title",
      args.title,
      "--body-file",
      bodyFile,
    ];
    if (args.draft) ghArgs.push("--draft");

    const create = await runner.run("gh", ghArgs, { cwd: args.cwd });
    if (create.code !== 0) {
      throw new Error(`gh pr create failed (${create.code}): ${create.stderr.slice(0, 500)}`);
    }

    const url = create.stdout.trim();
    const numberMatch = url.match(/\/pull\/(\d+)/);
    if (!numberMatch) {
      log.error({ url, stderr: create.stderr }, "failed to parse PR number from gh output");
      throw new Error(`gh pr create returned unparseable output: ${url}`);
    }

    return { url, number: Number(numberMatch[1]) };
  } finally {
    await fs.rm(bodyFile, { force: true }).catch(() => {});
  }
}
