// Command-position shell syntax words that introduce another command: a
// classifier that only looks at argv[0] would see `if`/`do`/`!` and miss the
// real program behind them (`if rm x`, `do rm $f`, `! rm x`, `{ rm x; }`).
// These are transparent prefixes — strip them so the true verb classifies.
export const SHELL_KEYWORD_WORDS = new Set([
  "if",
  "then",
  "elif",
  "else",
  "fi",
  "do",
  "done",
  "while",
  "until",
  "for",
  "select",
  "in",
  "case",
  "esac",
  "{",
  "}",
  "!",
]);

// `builtin` is normally a transparent prefix, but `builtin -f/--load` injects
// a shared library and `-d/--delete` removes builtins — keep it as the
// program in that case so the deny below fires instead of stripping to an
// innocent-looking flag.
export const BUILTIN_MUTATE_FLAGS = new Set(["-f", "--load", "-d", "--delete"]);

