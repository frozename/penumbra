// Deep-relative: node_modules/@penumbra/config in this worktree symlinks to the
// pre-change checkout, so the package specifier would not resolve this new export.
// Resolves to the same file as @penumbra/config post-land.
import {
  isGeneratorOwned,
  pruneOwnedOnly,
  upsertManagedFields,
} from "../../../config/src/generator/upsert.js";
import { assertPruneSafe } from "../../../config/src/generator/routing-refs.js";
import { existsSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import YAML from "yaml";

import { executeConfigSplitWrite } from "./config-split.js";

const PROVENANCE_SOURCE = "llamactl-sync-local";
const DEFAULT_PROXY_BASE_URL = "http://127.0.0.1:7944";

export interface ConfigSyncLocalResult {
  exitCode: number;
  stdout: string[];
  stderr: string[];
}

export interface RunConfigSyncLocalOpts {
  apply?: boolean;
  dryRun?: boolean;
  configDir?: string;
  env?: Record<string, string | undefined>;
  inventory?: () => Promise<LlamactlInventory>;
  reloadConfig?: () => Promise<unknown>;
  validateAgentsConfig?: (value: unknown) => AgentsConfig;
  storageRoot?: string;
}

interface GeneratedSeat {
  name: string;
  model: LlamactlModelInventory;
  baseUrl: string;
  nodeName: string;
}

function resolveConfigDir(env: Record<string, string | undefined>): string {
  if (env.PENUMBRA_CONFIG_DIR && env.PENUMBRA_CONFIG_DIR.length > 0) return env.PENUMBRA_CONFIG_DIR;
  if (env.XDG_CONFIG_HOME && env.XDG_CONFIG_HOME.length > 0) {
    return join(env.XDG_CONFIG_HOME, "penumbra");
  }
  const home = env.HOME && env.HOME.length > 0 ? env.HOME : homedir();
  return join(home, ".config", "penumbra");
}

function slugifySeatPart(value: string): string {
  return stripModelFileExtension(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function stripModelFileExtension(id: string): string {
  const lower = id.toLowerCase();
  if (
    lower.endsWith(".gguf") ||
    lower.endsWith(".ggml") ||
    lower.endsWith(".safetensors") ||
    lower.endsWith(".onnx") ||
    lower.endsWith(".bin") ||
    lower.endsWith(".pt") ||
    lower.endsWith(".pth") ||
    lower.endsWith(".ckpt")
  ) {
    return id.slice(0, id.lastIndexOf("."));
  }
  return id;
}

function modelSeatIdSource(modelId: string): string {
  const slash = modelId.lastIndexOf("/");
  if (slash < 0) return modelId;
  if (slash === modelId.length - 1) return modelId.slice(0, -1);
  return modelId.slice(0, slash);
}

function generatedSeatForModel(model: LlamactlModelInventory): GeneratedSeat {
  const slug = slugifySeatPart(modelSeatIdSource(model.id)) || "model";
  const nodeName = model.node?.name ?? model.owned_by ?? "local";
  return {
    name: `local-${slug}-http`,
    model,
    baseUrl: model.node?.endpoint ?? DEFAULT_PROXY_BASE_URL,
    nodeName,
  };
}

function defaultsForModel(
  modelId: string,
): Pick<AgentConfig, "roles" | "tags" | "description" | "quirks"> {
  const lower = modelId.toLowerCase();
  if (lower.includes("embed") || lower.includes("bge")) {
    return {
      roles: ["embedder"],
      tags: ["local", "embedding"],
      description: `Local served model ${modelId}`,
      quirks: ["Generated by penumbra config sync-local; verify before broad routing."],
    };
  }
  if (lower.includes("code") || lower.includes("coder")) {
    return {
      roles: ["executor", "reviewer"],
      tags: ["local", "coding"],
      description: `Local served model ${modelId}`,
      quirks: ["Generated by penumbra config sync-local; benchmark before premium routing."],
    };
  }
  return {
    roles: ["executor"],
    tags: ["local"],
    description: `Local served model ${modelId}`,
    quirks: ["Generated by penumbra config sync-local; benchmark before premium routing."],
  };
}

const MANAGED_FIELDS = [
  "name",
  "adapter",
  "api_provider",
  "pricing_mode",
  "options.baseUrl",
  "options.model",
  "options.apiKeyKeychain",
] as const;

// Narrower than MANAGED_FIELDS (which also drives the actual upsert merge):
// this is only the provenance stamp recorded on a freshly generated seat, and
// must stay pinned to what sync-local has always stamped.
const STAMPED_MANAGED_FIELDS = [
  "options.baseUrl",
  "options.model",
  "options.apiKeyKeychain",
] as const;

function buildGeneratedSeat(generated: GeneratedSeat): AgentConfig {
  const defaults = defaultsForModel(generated.model.id);
  return {
    name: generated.name,
    adapter: "openai-compat-http",
    api_provider: "local",
    pricing_mode: "api",
    roles: defaults.roles,
    auto_approve_to: [],
    tags: defaults.tags,
    quirks: defaults.quirks,
    description: defaults.description,
    provenance: {
      source: PROVENANCE_SOURCE,
      managed_fields: [...STAMPED_MANAGED_FIELDS],
    },
    options: {
      baseUrl: generated.baseUrl,
      model: generated.model.id,
      apiKeyKeychain: `llamactl/${generated.nodeName}`,
    },
  };
}

function upsertSeat(existing: AgentConfig | undefined, generated: GeneratedSeat): AgentConfig {
  // A seat that lost its roles entirely (e.g. never set) falls back to
  // model-inferred defaults instead of being upserted into a roleless seat.
  const managedFields =
    existing?.roles.length === 0 ? [...MANAGED_FIELDS, "roles"] : MANAGED_FIELDS;
  const merged = upsertManagedFields(existing, buildGeneratedSeat(generated), managedFields);
  const options = { ...merged.options };
  delete options.apiKey;
  delete options.apiKeyEnv;
  delete options.apiKeyFile;
  return { ...merged, options };
}

function buildSyncedAgentsConfig(
  current: AgentsConfig,
  inventory: LlamactlInventory,
  routing: RoutingConfig,
): { config: AgentsConfig; upserts: string[]; prunes: string[] } {
  const handAuthoredModels = new Set(
    current.agents.flatMap((agent) => {
      const model = agent.options?.model;
      if (typeof model !== "string") return [];
      return isGeneratorOwned(agent, PROVENANCE_SOURCE) ? [] : [model];
    }),
  );

  const generated = inventory.models
    .filter((model) => !handAuthoredModels.has(model.id))
    .map(generatedSeatForModel);
  const generatedNames = new Set(generated.map((seat) => seat.name));
  const upserts: string[] = [];
  const byName = new Map(current.agents.map((agent) => [agent.name, agent] as const));

  for (const seat of generated) {
    byName.set(seat.name, upsertSeat(byName.get(seat.name), seat));
    upserts.push(seat.name);
  }

  const { agents, prunes } = pruneOwnedOnly(
    [...byName.values()],
    generatedNames,
    PROVENANCE_SOURCE,
  );
  assertPruneSafe(prunes, routing);

  return {
    config: {
      ...current,
      agents,
    },
    upserts,
    prunes,
  };
}

function readAgentsConfig(configDir: string): AgentsConfig {
  const path = join(configDir, "agents.yaml");
  const parsed = YAML.parse(readFileSync(path, "utf8")) as unknown;
  return AgentsConfigSchema.parse(parsed);
}

// No routing.yaml present means no routing references exist to violate, so an
// absent file resolves to an empty routing config rather than failing sync-local.
function readRoutingConfig(configDir: string): RoutingConfig {
  const path = join(configDir, "routing.yaml");
  if (!existsSync(path)) return RoutingConfigSchema.parse({});
  const parsed = YAML.parse(readFileSync(path, "utf8")) as unknown;
  return RoutingConfigSchema.parse(parsed);
}

async function defaultReloadConfig(storageRoot: string): Promise<unknown> {
  const portPath = join(storageRoot, "port");
  const tokenPath = join(storageRoot, "token");
  if (!existsSync(portPath) || !existsSync(tokenPath)) {
    return { skipped: "daemon metadata not found" };
  }
  const port = Number(readFileSync(portPath, "utf8").trim());
  const token = readFileSync(tokenPath, "utf8").trim();
  if (!Number.isInteger(port) || port < 1 || port > 65535 || token.length === 0) {
    return { skipped: "daemon metadata invalid" };
  }
  const response = await fetch(`http://127.0.0.1:${String(port)}/agentchat/reload`, {
    method: "POST",
    headers: { authorization: `Bearer ${token}` },
  });
  if (!response.ok) return { skipped: `daemon reload returned HTTP ${String(response.status)}` };
  return response.json();
}

export async function runConfigSyncLocal(
  opts: RunConfigSyncLocalOpts = {},
): Promise<ConfigSyncLocalResult> {
  const stdout: string[] = [];
  const stderr: string[] = [];
  const env = opts.env ?? process.env;
  const configDir = opts.configDir ?? resolveConfigDir(env);
  const validateAgentsConfig =
    opts.validateAgentsConfig ?? ((value) => AgentsConfigSchema.parse(value));
  const dryRun = opts.dryRun === true || opts.apply !== true;

  let current: AgentsConfig;
  try {
    current = readAgentsConfig(configDir);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    stderr.push(
      `penumbra config sync-local: failed to read ${join(configDir, "agents.yaml")}: ${message}`,
    );
    return { exitCode: 1, stdout, stderr };
  }

  const inventory = await (opts.inventory ?? (() => collectLlamactlInventory({ env })))();
  if (inventory.messages.length > 0) stdout.push(...inventory.messages);
  if (inventory.models.length === 0) {
    stdout.push("penumbra config sync-local: no local models discovered; agents.yaml unchanged");
    return { exitCode: 0, stdout, stderr };
  }

  let config: AgentsConfig;
  let upserts: string[];
  let prunes: string[];
  try {
    const routing = readRoutingConfig(configDir);
    ({ config, upserts, prunes } = buildSyncedAgentsConfig(current, inventory, routing));
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    stderr.push(`penumbra config sync-local: ${message}`);
    return { exitCode: 1, stdout, stderr };
  }
  for (const name of upserts) stdout.push(`${dryRun ? "would upsert" : "upserted"} ${name}`);
  for (const name of prunes) stdout.push(`${dryRun ? "would prune" : "pruned"} ${name}`);

  let validated: AgentsConfig;
  try {
    validated = validateAgentsConfig(config);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    stderr.push(`penumbra config sync-local: schema validation failed: ${message}`);
    return { exitCode: 1, stdout, stderr };
  }

  if (dryRun) {
    stdout.push("penumbra config sync-local: dry run; pass --apply to write agents.yaml");
    return { exitCode: 0, stdout, stderr };
  }

  const writeCode = executeConfigSplitWrite([["agents.yaml", validated]], [], configDir);
  if (writeCode !== 0) return { exitCode: writeCode, stdout, stderr };

  try {
    const reload = await (
      opts.reloadConfig ??
      (() =>
        defaultReloadConfig(
          resolveDaemonStorageRoot({ explicit: opts.storageRoot ?? env.PENUMBRA_STORAGE_ROOT }),
        ))
    )();
    if (
      reload &&
      typeof reload === "object" &&
      "skipped" in reload &&
      typeof reload.skipped === "string"
    ) {
      stdout.push(`penumbra config sync-local: daemon reload skipped: ${reload.skipped}`);
    } else {
      stdout.push("penumbra config sync-local: daemon reload requested");
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    stdout.push(`penumbra config sync-local: daemon reload skipped: ${message}`);
  }

  return { exitCode: 0, stdout, stderr };
}
